export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { tr, en };

export function translate(lang: Lang, key: MessageKey, params?: Record<string, string | number>): string {
  const template = MESSAGES[lang][key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export function detectInitialLang(stored: string | null, browserLang: string | undefined): Lang {
  if (stored === 'tr' || stored === 'en') return stored;
  return browserLang?.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function readInitialLang(): Lang {
  let stored: string | null = null;
  try {
    stored = localStorage.getItem(LANG_STORAGE_KEY);
  } catch {
    // Private mode or blocked storage: fall back to the browser language.
  }
  return detectInitialLang(stored, typeof navigator !== 'undefined' ? navigator.language : undefined);
}

export interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MessageKey, params?: Record<string, string | number>) => string;
}

export const I18nContext = createContext<I18nValue>({
  lang: 'tr',
  setLang: () => {},
  t: (key, params) => translate('tr', key, params),
});

export const useI18n = () => useContext(I18nContext);
